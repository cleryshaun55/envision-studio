-- 2) Create an owner account in Authentication > Users.
-- 3) Insert that account's UUID into public.admin_users (example below).

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  title text not null,
  category text not null,
  description text not null default '',
  image_url text not null,
  label text not null default 'PROJECT',
  published boolean not null default true
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text not null,
  whatsapp text,
  business text,
  service text not null,
  description text not null,
  budget text,
  deadline date
);

alter table public.admin_users enable row level security;
alter table public.projects enable row level security;
alter table public.enquiries enable row level security;

-- Public visitors can see only published portfolio projects.
drop policy if exists "Public can view published projects" on public.projects;
create policy "Public can view published projects"
on public.projects for select to anon, authenticated
using (published = true or public.is_admin());

-- Only an authenticated admin can add, edit or remove portfolio projects.
drop policy if exists "Admins can insert projects" on public.projects;
create policy "Admins can insert projects"
on public.projects for insert to authenticated
with check (public.is_admin());

drop policy if exists "Admins can update projects" on public.projects;
create policy "Admins can update projects"
on public.projects for update to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins can delete projects" on public.projects;
create policy "Admins can delete projects"
on public.projects for delete to authenticated
using (public.is_admin());

-- Visitors can submit enquiries. Only admins can read or delete them.
drop policy if exists "Anyone can submit an enquiry" on public.enquiries;
create policy "Anyone can submit an enquiry"
on public.enquiries for insert to anon, authenticated
with check (
  length(trim(name)) > 0 and
  length(trim(email)) > 3 and
  length(trim(service)) > 0 and
  length(trim(description)) > 0
);

drop policy if exists "Admins can read enquiries" on public.enquiries;
create policy "Admins can read enquiries"
on public.enquiries for select to authenticated
using (public.is_admin());

drop policy if exists "Admins can delete enquiries" on public.enquiries;
create policy "Admins can delete enquiries"
on public.enquiries for delete to authenticated
using (public.is_admin());

